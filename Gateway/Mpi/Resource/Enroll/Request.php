namespace Braspag\BraspagPagador\Gateway\Mpi\Resource\Enroll;

class Request implements RequestInterface
{
    /**
     * @var array
     */
    private $payload;

    /**
     * @param array $payload
     */
    public function __construct(array $payload)
    {
        $this->payload = $payload;
    }

    /**
     * {@inheritdoc}
     */
    public function toArray()
    {
        return $this->payload;
    }
}
